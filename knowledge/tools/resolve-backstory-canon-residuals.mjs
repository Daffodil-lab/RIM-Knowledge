let changedFiles = 0;
for (const [id, replacements] of Object.entries(edits)) {
  const group = id.startsWith("C") ? "formation" : "mastery";
  const file = path.join(root, "knowledge", "backstories", group, `SHION_${id}.md`);
  let text = fs.readFileSync(file, "utf8");
  const sourceIndex = text.indexOf("\n## 出典");
  if (sourceIndex < 0) throw new Error(`missing source section: ${file}`);
  let prefix = text.slice(0, sourceIndex);
  const suffix = text.slice(sourceIndex);
  const lines = prefix.split("\n");
  for (const [from, to] of replacements) {
    let hits = 0;
    for (let i = 0; i < lines.length; i += 1) {
      if (lines[i].startsWith("source_section:")) continue;
      if (lines[i].includes(from)) {
        lines[i] = lines[i].split(from).join(to);
        hits += 1;
      }
    }
    if (hits === 0 && !lines.some((line) => !line.startsWith("source_section:") && line.includes(to))) {
      throw new Error(`expected text not found in ${id}: ${from}`);
    }
  }
  const next = `${lines.join("\n")}${suffix}`;
  if (next !== text) {
    fs.writeFileSync(file, next, "utf8");
    changedFiles += 1;
  }
}

